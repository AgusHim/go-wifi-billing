// ── Partner portal login accounts ──────────────────────────────────────────

func validatePartnerAccount(in dto.PartnerAccountRequest) error {
	if strings.TrimSpace(in.Name) == "" {
		return errors.New("account name is required")
	}
	if !strings.Contains(strings.TrimSpace(in.Email), "@") {
		return errors.New("a valid account email is required")
	}
	if password := strings.TrimSpace(in.Password); password != "" && len(password) < 6 {
		return errors.New("account password must be at least 6 characters")
	}
	return nil
}

// CreatePartnerAccount creates a portal login account for an existing partner
// and links it as a partner member.
func (s *partnerService) CreatePartnerAccount(partnerID uuid.UUID, in dto.PartnerAccountRequest, actorID uuid.UUID) (*PartnerAccountResult, error) {
	partner, err := s.repo.FindPartner(partnerID)
	if err != nil {
		return nil, errors.New("partner not found")
	}
	return s.createPartnerAccount(*partner, in, actorID)
}

func (s *partnerService) createPartnerAccount(partner models.Partner, in dto.PartnerAccountRequest, actorID uuid.UUID) (*PartnerAccountResult, error) {
	if err := validatePartnerAccount(in); err != nil {
		return nil, err
	}
	email := strings.TrimSpace(in.Email)
	generatedPassword := ""

	// An existing user may simply be linked instead of created again.
	user, err := s.userRepo.GetByEmail(email)
	if err != nil || user == nil {
		var createErr error
		user, generatedPassword, createErr = s.newPortalUser(in)
		if createErr != nil {
			return nil, createErr
		}
	} else if existing, memberErr := s.repo.FindMemberByPartnerAndUser(partner.ID, user.ID); memberErr == nil && existing != nil {
		return nil, errors.New("this email already has access to this partner")
	}

	// The first account becomes the partner owner, later ones are members.
	role := "member"
	if count, countErr := s.repo.CountMembers(partner.ID); countErr == nil && count == 0 {
		role = "owner"
	}
	member := &models.PartnerMember{PartnerID: partner.ID, UserID: user.ID, Role: role, Status: "active"}
	if err := s.repo.CreateMember(member); err != nil {
		return nil, err
	}

	result := &PartnerAccountResult{
		MemberID: member.ID, UserID: user.ID,
		PartnerID: partner.ID, PartnerName: partner.Name, PartnerCode: partner.Code,
		Name: user.Name, Email: user.Email,
		Phone: user.Phone, Role: role, Status: member.Status, IsActive: user.IsActive,
		TemporaryPassword: generatedPassword,
	}
	if in.SendInvite {
		result.InviteSent = s.sendPartnerInvite(partner, user, generatedPassword)
	}
	return result, nil
}

// newPortalUser creates a `customer` user, which is the role that already
// carries the self.partner.* permissions used by the partner portal.
func (s *partnerService) newPortalUser(in dto.PartnerAccountRequest) (*models.User, string, error) {
	role, err := s.userRepo.GetRoleByKey("customer")
	if err != nil {
		return nil, "", fmt.Errorf("customer role is not available: %w", err)
	}
	password := strings.TrimSpace(in.Password)
	generated := ""
	if password == "" {
		password = generateTemporaryPassword()
		generated = password
	}
	hashed, err := bcrypt.GenerateFromPassword([]byte(password), bcrypt.DefaultCost)
	if err != nil {
		return nil, "", err
	}
	user := &models.User{
		Name: strings.TrimSpace(in.Name), Email: strings.TrimSpace(in.Email), Phone: strings.TrimSpace(in.Phone),
		Password: string(hashed), Role: "user", RoleID: &role.ID, IsActive: true,
	}
	if err := s.userRepo.Create(user); err != nil {
		return nil, "", err
	}
	return user, generated, nil
}

func generateTemporaryPassword() string {
	const alphabet = "abcdefghijkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789"
	buf := make([]byte, 10)
	for i := range buf {
		index, err := rand.Int(rand.Reader, big.NewInt(int64(len(alphabet))))
		if err != nil {
			buf[i] = alphabet[i%len(alphabet)]
			continue
		}
		buf[i] = alphabet[index.Int64()]
	}
	return string(buf)
}

// sendPartnerInvite emails the portal address and the generated password. The
// password is only included when it was generated by the server.
func (s *partnerService) sendPartnerInvite(partner models.Partner, user *models.User, generatedPassword string) bool {
	if s.brevo == nil {
		return false
	}
	body := fmt.Sprintf("<p>Halo %s,</p><p>Akun portal mitra <strong>%s</strong> telah dibuat.</p><p>Email: %s</p>", user.Name, partner.Name, user.Email)
	if generatedPassword != "" {
		body += fmt.Sprintf("<p>Kata sandi sementara: <strong>%s</strong></p><p>Mohon segera ganti kata sandi setelah masuk.</p>", generatedPassword)
	} else {
		body += "<p>Gunakan kata sandi yang diberikan oleh staf Cantika.net.</p>"
	}
	if _, sendErr := s.brevo.Send(user.Email, "Akses Portal Mitra "+partner.Name, body); sendErr != "" {
		log.Printf("[partner-account] invite email to %s failed: %s", user.Email, sendErr)
		return false
	}
	return true
}

